export const DICTS: Record<Lang, Dict> = { pl, en, de }

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.pl[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(formatVar(lang, v))
  return s
}

const LOCALE: Record<Lang, string> = { pl: 'pl-PL', en: 'en-GB', de: 'de-DE' }
export const locale = (l: Lang) => LOCALE[l]

function formatVar(lang: Lang, v: string | number): string {
  if (typeof v !== 'number') return v
  return new Intl.NumberFormat(LOCALE[lang], { maximumFractionDigits: Math.abs(v) >= 1000 ? 0 : 2 }).format(v)
}

export function money(lang: Lang, v: number, digits = 0): string {
  return new Intl.NumberFormat(LOCALE[lang], { style: 'currency', currency: 'PLN', maximumFractionDigits: digits, minimumFractionDigits: digits }).format(v)
}
export function percent(lang: Lang, fraction: number | null | undefined, digits = 1, sign = false): string {
  if (fraction === null || fraction === undefined || !Number.isFinite(fraction)) return '–'
  return new Intl.NumberFormat(LOCALE[lang], { style: 'percent', maximumFractionDigits: digits, minimumFractionDigits: digits, signDisplay: sign ? 'exceptZero' : 'auto' }).format(fraction)
}
export function dateFmt(lang: Lang, iso: string): string {
  if (!iso) return '–'
  return new Intl.DateTimeFormat(LOCALE[lang], { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(new Date(iso + 'T00:00:00Z'))
}

/** a rate given in percent (5.35 → "5,35%" in Polish) */
export function rate(lang: Lang, pct: number, digits = 2): string {
  return new Intl.NumberFormat(LOCALE[lang], { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(pct) + '%'
}
