test('encrypted backup: export, then restore in a fresh browser; wrong password is refused', async ({ page, browser }) => {
  await addDeposit(page)
  await page.getByTestId('nav-settings').click()
  await page.getByTestId('s-password').fill('rodzinna-kopia-2026')
  const dl = page.waitForEvent('download')
  await page.getByTestId('s-export').click()
  const file = await (await dl).path()
  const fresh = await browser.newContext()
  const p2 = await fresh.newPage()
  await p2.goto(page.url().replace(/#.*/, '') + '#settings')
  await p2.getByTestId('s-password').fill('zle-haslo-123')
  await p2.getByTestId('s-import').setInputFiles(file!)
  await expect(p2.getByTestId('s-msg')).toContainText('Złe hasło')
  await p2.getByTestId('s-password').fill('rodzinna-kopia-2026')
  await p2.getByTestId('s-import').setInputFiles(file!)
  await p2.waitForLoadState('load')
  await p2.goto(page.url().replace(/#.*/, '') + '#assets')
  await expect(p2.locator('[data-testid^="asset-"]')).toHaveCount(1)
  await expect(p2.locator('[data-testid^="asset-"]')).toContainText('BankX')
  await fresh.close()
})

