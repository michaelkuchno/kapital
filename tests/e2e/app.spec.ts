test('the family portfolio: EDO, deposit, two GPW shares → values, totals and insights', async ({ page }) => {
  await addBond(page, '250 000', iso(-190))
  await expect(page.getByTestId('form-problem')).toHaveCount(0)
  const bondCard = page.locator('[data-testid^="asset-"]').filter({ hasText: 'EDO' })
  await expect(bondCard).toContainText('EDO')
  await expect(bondCard.getByTestId('bond-count')).toHaveText(/^2\s?500$/) // Polish: no separator in 4-digit numbers
  await expect(bondCard).toContainText(/EDO\d{4}/)
  const bondValue = await num(page, (await bondCard.locator('[data-testid^="value-"]').getAttribute('data-testid'))!)
  expect(bondValue).toBeGreaterThan(250_000)
  expect(bondValue).toBeLessThan(250_000 * 1.06)
  await addDeposit(page)
  await addStock(page, 'SKARBIEC', '500', '15000')
  await addStock(page, 'SNTVERSE', '10000', '53400')
  await expect(page.locator('[data-testid^="asset-"]')).toHaveCount(4)
  // the share price comes from the GPW data (no "missing price" note)
  await expect(page.getByText('Brak kursu')).toHaveCount(0)
  const snt = page.locator('[data-testid^="asset-"]').filter({ hasText: 'SNTVERSE' })
  const sntGain = await num(page, (await snt.locator('[data-testid^="gain-"]').getAttribute('data-testid'))!)
  expect(sntGain).toBeLessThan(0)
  await expect(snt).toContainText('Potrzebny wzrost')

  await page.getByTestId('nav-dashboard').click()
  const total = await num(page, 'total-value')
  expect(total).toBeGreaterThan(250_000 + 60_000 + 40_000)
  await expect(page.getByTestId('class-bonds-inflation')).toBeVisible()
  await expect(page.getByTestId('class-equities')).toBeVisible()
  await expect(page.getByTestId('class-deposits')).toBeVisible()

  await page.getByTestId('nav-insights').click()
  await expect(page.locator('[data-testid^="insight-loss-"]')).toContainText('SNTVERSE')
  await expect(page.locator('[data-testid^="insight-deposit-ending-"]')).toBeVisible()
  await expect(page.locator('[data-testid^="insight-deposit-promo-"]')).toBeVisible()
  await expect(page.getByTestId('insight-single-stocks-only')).toBeVisible()
  await expect(page.getByTestId('insight-emergency-unknown')).toBeVisible()
  // every insight has sources
  const why = page.locator('[data-testid^="insight-loss-"] details')
  await why.locator('summary').click()
  await expect(why).toContainText('Shefrin')
  // warnings come first
  const sev = await page.locator('[data-testid^="insight-"]').evaluateAll((els) => els.map((e) => e.getAttribute('data-severity')))
  const order = { warn: 0, tip: 1, info: 2, ok: 3 } as Record<string, number>
  for (let i = 1; i < sev.length; i++) expect(order[sev[i - 1]!]).toBeLessThanOrEqual(order[sev[i]!])

  // data stays after a reload (IndexedDB)
  await page.reload()
  await page.getByTestId('nav-assets').click()
  await expect(page.locator('[data-testid^="asset-"]')).toHaveCount(4)
})

test('form validation, decimals with a comma, edit and delete', async ({ page }) => {
  await page.getByTestId('nav-assets').click()
  await page.getByTestId('add-asset').click()
  await page.getByTestId('kind-deposit').click()
  await page.getByTestId('f-amount').fill('')
  await expect(page.getByTestId('form-problem')).toBeVisible()
  await expect(page.getByTestId('f-save')).toBeDisabled()
  await page.getByTestId('f-amount').fill('abc')
  await expect(page.getByTestId('f-save')).toBeDisabled()
  await page.getByTestId('f-amount').fill('25 000,50')
  await page.getByTestId('f-rate').fill('5,35')
  await expect(page.getByTestId('f-rate')).toHaveValue('5,35')
  await expect(page.getByTestId('f-save')).toBeEnabled()
  await page.getByTestId('f-save').click()
  const card = page.locator('[data-testid^="asset-"]').first()
  await expect(card).toContainText('25')
  const id = (await card.getAttribute('data-testid'))!.slice(6)
  await page.getByTestId(`edit-${id}`).click()
  await expect(page.getByTestId('f-rate')).toHaveValue('5,35')
  await page.getByTestId('f-amount').fill('30000')
  await page.getByTestId('f-save').click()
  await expect(page.getByTestId(`value-${id}`)).toHaveAttribute('data-value', /^30\d{3}/)
  await page.getByTestId(`delete-${id}`).click()
  await expect(page.locator('[data-testid^="asset-"]')).toHaveCount(0)
  // Escape closes the dialog without saving
  await page.getByTestId('add-asset').click()
  await page.getByTestId('kind-cash').click()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('asset-form')).toBeHidden()
  await expect(page.locator('[data-testid^="asset-"]')).toHaveCount(0)
})

